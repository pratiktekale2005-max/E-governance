"""
Pre-screening Engine Standard Response & Results Models (Module 6, 8, 11)
"""
from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ThreeValuedLogic(str, Enum):
    TRUE = "TRUE"
    FALSE = "FALSE"
    UNKNOWN = "UNKNOWN"


class PreScreeningStatus(str, Enum):
    LIKELY_MATCH = "likely_match"
    POSSIBLE_MATCH = "possible_match"
    MORE_INFORMATION_REQUIRED = "more_information_required"
    APPEARS_NOT_TO_MATCH = "appears_not_to_match"
    SOURCE_CONFLICT = "source_conflict"
    STALE_RULE = "stale_rule"
    OFFICIAL_VERIFICATION_REQUIRED = "official_verification_required"


class ConditionEvaluationResult(BaseModel):
    field: str
    result: ThreeValuedLogic
    description: str
    reason: str


class RequiredDocumentDetail(BaseModel):
    document_name: str
    issuing_authority: str
    official_download_link: Optional[str] = None
    is_alternative: bool = False
    alternative_group_id: Optional[str] = None


class PreScreeningSchemeResult(BaseModel):
    scheme_id: str
    scheme_name: str
    decision_type: str = "pre_screening"
    status: PreScreeningStatus
    ranking_score: int
    matched_conditions: List[str] = Field(default_factory=list)
    missing_information: List[str] = Field(default_factory=list)
    conflicting_conditions: List[str] = Field(default_factory=list)
    required_documents: List[RequiredDocumentDetail] = Field(default_factory=list)
    ranking_reasons: List[str] = Field(default_factory=list)
    official_verification_required: bool = True
    sources: List[Dict[str, Any]] = Field(default_factory=list)


class PreScreeningCheckResponse(BaseModel):
    user_id: Optional[str] = None
    timestamp: str
    schemes_evaluated: int
    matched_schemes: List[PreScreeningSchemeResult] = Field(default_factory=list)
    missing_profile_fields: List[str] = Field(default_factory=list)
    follow_up_questions: List[str] = Field(default_factory=list)
    llm_explanation: Optional[str] = Field(None, description="Plain language explanation generated by LLM from deterministic results")
